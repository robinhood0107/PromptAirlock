TEST(DetectKrAccounts, EveryFormatRow) {
    for (std::size_t i = 0; i < kr_cases.size(); ++i) {
        const auto& f = pd::data::kr_account_formats[i];
        const auto& c = kr_cases[i];
        ASSERT_EQ(c.case_name, f.case_name) << i;
        const std::string lead = f.needs_context ? "입금 계좌 " : "번호 ";
        EXPECT_TRUE(account_found(lead + std::string(c.positive) + " 입니다", c.positive)) << f.case_name;
        EXPECT_FALSE(account_found("번호 " + std::string(c.negative) + " 입니다", c.negative)) << f.case_name;
    }
}
