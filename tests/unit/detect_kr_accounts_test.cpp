bool account_found(std::string_view text, std::string_view digits) {
    static const auto d = *pd::Detectors::make({});
    const auto entities = d.detect_segment(text, pc::SegmentIndex{0});
    EXPECT_TRUE(entities);
    for (const auto& e : *entities) {
        if (e.type() == pc::EntityType::BankAccount &&
            text.substr(e.span().begin().value(), e.span().size()) == digits) {
            return true;
        }
    }
    return false;
}

